"""Catalog every GPU shader: local size, bindings, push-constant words used, header comment, .spv status.
Scans the shader folders that the speech-app and asr-gpu ports use. Writes GPU_SHADERS.md in the kit.
usage: python3 tools/catalog_shaders.py
Re-run after adding shaders; the table is generated, do not edit it by hand."""
import glob
import os
import re

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = [os.path.expanduser('~/speech-app/port/gpu'), os.path.expanduser('~/speech-app/port/gpu/fe'),
        os.path.expanduser('~/speech-app/port/stream'), os.path.expanduser('~/src/asr-gpu/shaders')]
PUSH = re.compile(r'\bp\.u\[(\d+)\]|\bU\((\d+)\)')


def catalog_one(path):
    src = open(path).read()
    local = re.search(r'local_size_x\s*=\s*(\d+)', src)
    binds = re.findall(r'layout\(std430,\s*binding\s*=\s*(\d+)\)\s*(readonly\s+)?buffer\s+\w+\s*\{\s*(\w+)\s+\w+\[\]', src)
    names = re.findall(r'binding\s*=\s*(\d+)\)[^{]*buffer\s+(\w+)\s*\{\s*(\w+)', src)
    push = set()
    for a, b in PUSH.findall(src):
        push.add(int(a or b))
    ps = re.findall(r'p\.u\[(\d+)\]', src)
    # note: the first 'U(n)' macro is defined in some shaders; both forms count
    comments = [l.strip('/ ').strip() for l in src.splitlines()[1:8] if l.startswith('//')]
    defines = re.findall(r'-D\w+|#define\s+\w+', src)
    spv = path[:-5] + '.spv'
    spv_ok = os.path.exists(spv)
    stale = spv_ok and os.path.getmtime(spv) < os.path.getmtime(path)
    return dict(name=os.path.basename(path)[:-5], dir=os.path.dirname(path), local=local.group(1) if local else '?',
                bindings=sorted({(int(b), n, t) for b, n, t in names}), push=sorted(push),
                comment=' '.join(comments)[:300], spv=('yes' if spv_ok else 'NO') + (' (stale)' if stale else ''))


def main():
    rows = []
    for d in DIRS:
        for p in sorted(glob.glob(os.path.join(d, '*.comp'))):
            rows.append(catalog_one(p))
    out = ['# GPU shader catalog (generated by tools/catalog_shaders.py)', '',
           'Push words: indices of p.u[] used by the shader (exec sends 32 words). Bindings: binding index, buffer name, element type.',
           'Stale = .spv older than .comp (recompile with glslc -O).', '',
           '| shader | folder | local | bindings | push words used | .spv | header comment |', '|---|---|---|---|---|---|---|']
    for r in rows:
        b = ', '.join(f'{i}:{n}({t})' for i, n, t in r['bindings'])
        pw = ','.join(map(str, r['push'])) if r['push'] else '-'
        folder = r['dir'].replace(os.path.expanduser('~'), '~')
        out.append(f"| {r['name']} | {folder} | {r['local']} | {b} | {pw} | {r['spv']} | {r['comment']} |")
    text = '\n'.join(out) + '\n'
    open(os.path.join(KIT, 'GPU_SHADERS.md'), 'w').write(text)
    print(f'{len(rows)} shaders -> GPU_SHADERS.md')


if __name__ == '__main__':
    main()
