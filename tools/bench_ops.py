"""Time each op type at the real nemo8 shapes (d=176, H=4, dh=44, ff=704, k=31) for a 10 s clip (T=251 frames).
Uses the exec batch runner (submit+wait time per op, 20 repeats). Writes GPU_TIMINGS_T<T>.md in the kit.
usage: python3 tools/bench_ops.py [T]"""
import os
import sys
import numpy as np
KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, KIT)
from gpuport import Arena, Weights, Plan, ops
from gpuport.timing import time_op
from gpuport.config import WORK_DIR, MIN_WORKGROUPS

T = int(sys.argv[1]) if len(sys.argv) > 1 else 251
d, H, ff, k = 176, 4, 704, 31
dh = d // H; NP = 2 * T - 1; JB = (T + 3) // 4; IB = (T + 1) // 2
rng = np.random.default_rng(0)
w = Weights()
mm = {'ff': w.put_mm(rng.standard_normal((ff, d)).astype(np.float32) * 0.05, np.zeros(ff)),
      'qkv': w.put_mm(rng.standard_normal((3 * d, d)).astype(np.float32) * 0.05, np.zeros(3 * d)),
      'ff2': w.put_mm(rng.standard_normal((d, ff)).astype(np.float32) * 0.05, np.zeros(d)),
      'pos': w.put_mm(rng.standard_normal((d, d)).astype(np.float32) * 0.05, np.zeros(d))}
gO = w.put(np.ones(2 * d, np.float32)); pbuO = w.put(np.zeros(d, np.float32)); pbvO = w.put(np.zeros(d, np.float32))
dwO = w.put(rng.standard_normal((k, d)).astype(np.float32)); dwbO = w.put(np.zeros(d, np.float32))
path = w.save(os.path.join(WORK_DIR, f'bench_{T}'))

ar = Arena()
X = ar.alloc('X', T * d); Y = ar.alloc('Y', T * d); H2 = ar.alloc('H2', T * ff); QKV = ar.alloc('QKV', T * 3 * d)
PE = ar.alloc('PE', NP * d); P = ar.alloc('P', NP * d); SC = ar.alloc('SC', H * T * T); ATT = ar.alloc('ATT', T * d)
GL = ar.alloc('GL', T * d); CV = ar.alloc('CV', T * d)
arena = np.zeros(ar.used(), np.float32) + 0.01
push = [T, d, H, dh, QKV, P, SC, pbuO, pbvO]

cases = [
 ('gemm12 FF1 (M=T,K=176,N=704)', lambda p: ops.gemm12(p, X, T, mm['ff'], H2)),
 ('gemm12 QKV (M=T,K=176,N=528)', lambda p: ops.gemm12(p, X, T, mm['qkv'], QKV)),
 ('gemm12 FF2 (M=T,K=704,N=176)', lambda p: ops.gemm12(p, H2, T, mm['ff2'], Y)),
 ('gemm12 pos (M=2T-1,K=176,N=176)', lambda p: ops.gemm12(p, PE, NP, mm['pos'], P)),
 ('pe_gen', lambda p: p.dispatch('pe_gen', 64, NP * d, [T, d, PE])),
 ('att_scores5', lambda p: p.dispatch('att_scores5', 64, H * T * JB, push + [0] * 23)),
 ('att_scores6 (tiled, 2 rows x 4 keys)', lambda p: p.add('att_scores6', 64, max(MIN_WORKGROUPS, (H * ((T + 1) // 2) * JB + 63) // 64), 1, push + [0] * 23)),
 ('att_softmax', lambda p: p.dispatch('att_softmax', 64, H * T, push + [ATT] + [0] * 22)),
 ('att_pv6', lambda p: p.add('att_pv6', 64, max(MIN_WORKGROUPS, (H * IB * (dh // 4) + 63) // 64), 1, push + [ATT] + [0] * 22)),
 ('ln (T rows)', lambda p: ops.ln(p, T, d, X, Y, gO)),
 ('glu', lambda p: ops.glu(p, T, d, GL, CV)),
 ('dw4 (k=31)', lambda p: p.add('dw4', 64, max(MIN_WORKGROUPS, (d // 4 + 63) // 64), T, [T, d, k, GL, CV, dwO, dwbO])),
 ('silu (T*d)', lambda p: ops.silu(p, T * d, X, Y)),
 ('add (T*d)', lambda p: ops.add(p, T * d, X, Y, 0.5)),
]
rows = []
for name, build in cases:
    p = Plan()
    build(p)
    ms = time_op(p, arena, Y, 8, repeats=20, weights=path)
    rows.append((name, len(p), ms))
out = [f'# GPU op timings, T={T} (generated by tools/bench_ops.py)', '',
       'Submit+wait per op on the Pi (20 repeats, exec batch). Each op is one dispatch unless stated.', '',
       '| op | dispatches | ms per op |', '|---|---|---|']
out += [f'| {n} | {c} | {ms:.3f} |' for n, c, ms in rows]
text = '\n'.join(out) + '\n'
open(os.path.join(KIT, f'GPU_TIMINGS_T{T}.md'), 'w').write(text)
print(text)
