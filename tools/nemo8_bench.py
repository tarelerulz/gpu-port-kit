"""nemo8 speed proof: GPU path (kit plan, optimized front end) vs the host CPU encoder, on clip10s (10 s) and
clip5s (5 s). For each: wall time, GPU submit+wait, CPU seconds used by the process, and whether the transcript
matches the CPU transcript. Writes GPU_NEMO8_BENCH.md.
usage: python3 tools/nemo8_bench.py [repeats]"""
import os
import resource
import subprocess
import sys
import time
import wave
import numpy as np
KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, KIT); sys.path.insert(0, os.path.join(KIT, 'tests'))
import nemo8_rebuild as nb
from gpuport.server import ExecServer
from gpuport.config import WORK_DIR, merged_shader_dir

CPU = os.path.expanduser('~/speech-app/host/tasr_cli_a72')
MODEL = os.path.expanduser('~/speech-app/models/nemo8.tnm')
REPEATS = int(sys.argv[1]) if len(sys.argv) > 1 else 3


def cpu_s(ru):
    return ru.ru_utime + ru.ru_stime


def wav_of(clip, pcm):
    path = os.path.join(WORK_DIR, clip + '.wav')
    w = wave.open(path, 'wb'); w.setnchannels(1); w.setsampwidth(2); w.setframerate(16000)
    w.writeframes(pcm.tobytes()); w.close()
    return path


nr = nb.load_nemo_ref(); wt, L = nb.prepare(nr)
wpath = wt.save(os.path.join(WORK_DIR, 'nemo8_kit'))
TICK = os.sysconf('SC_CLK_TCK')


def proc_cpu(pid):
    f = open(f'/proc/{pid}/stat').read().rsplit(')', 1)[1].split()
    return (int(f[11]) + int(f[12])) / TICK          # utime + stime of a live process, seconds


srv = ExecServer(wpath, nb.SHADERS).start()
srv.run(nb.build(16000, L, optimized=True)[0], np.zeros(16000, np.float32), 0, 1)   # warm-up: pipelines, buffers
rows = []
for clip in ['clip10s', 'clip5s']:
    pcm = np.fromfile(os.path.join(nb.SPEECH_APP, clip + '.pcm'), '<i2')
    audio_s = len(pcm) / 16000
    plan, ar, R, T = nb.build(len(pcm), L, optimized=True)
    arena_in = pcm.astype(np.float32) / 32768.0
    g_wall, g_ms, g_cpu, text_g = [], [], [], ''
    for _ in range(REPEATS):
        c0 = proc_cpu(srv.proc.pid); t0 = time.time()
        out, ms = srv.run(plan, arena_in, R['LOG'], T * (L['V'] + 1))
        g_wall.append(time.time() - t0); g_ms.append(ms)
        g_cpu.append(proc_cpu(srv.proc.pid) - c0)
        text_g = nb.collapse(out.reshape(T, L['V'] + 1), L['tokens'], L['V'])
    wav = wav_of(clip, pcm)
    c_wall, c_cpu, text_c = [], [], ''
    for _ in range(REPEATS):
        r0 = resource.getrusage(resource.RUSAGE_CHILDREN); t0 = time.time()
        # 3 threads on cores 0-2: leave one core free so the Pi does not freeze (2026-11-05 freeze with 4 threads)
        res = subprocess.run(['taskset', '-c', '0,1,2', CPU, MODEL, wav], capture_output=True, text=True,
                             env={**os.environ, 'TASR_THREADS': '3', 'OMP_NUM_THREADS': '3'})   # greedy, no LM: same decoder as GPU
        c_wall.append(time.time() - t0)
        c_cpu.append(cpu_s(resource.getrusage(resource.RUSAGE_CHILDREN)) - cpu_s(r0))
        text_c = res.stdout.strip().split('\t')[-1] if res.stdout.strip() else res.stderr.strip()
    same = text_g.strip().lower() == text_c.strip().lower()
    rows.append((clip, audio_s, np.median(g_wall), np.median(g_ms), np.median(g_cpu), np.median(c_wall),
                 np.median(c_cpu), same))
    print(f'{clip}: GPU wall {np.median(g_wall):.2f} s (gpu {np.median(g_ms):.0f} ms, cpu {np.median(g_cpu):.2f} s); '
          f'CPU wall {np.median(c_wall):.2f} s (cpu {np.median(c_cpu):.2f} s); same text: {same}')
    print(f'   GPU: {text_g!r}\n   CPU: {text_c!r}')

out = ['# nemo8 speed: GPU path vs host CPU (generated by tools/nemo8_bench.py)', '',
       f'Median of {REPEATS} warm runs. GPU = kit plan (optimized front end) on a resident exec_server2 (weights loaded once). CPU = host tasr_cli_a72, greedy decode without the language model (same decoder as the GPU path). '
       'GPU CPU seconds = user+sys of the server process per run. CPU seconds = user+sys of the process (multi-threaded).', '',
       '| clip | audio s | GPU wall s | GPU kernel ms | GPU process CPU s | CPU wall s | CPU process CPU s | same text |',
       '|---|---|---|---|---|---|---|---|']
out += [f'| {c} | {a:.0f} | {gw:.2f} | {gm:.0f} | {gc:.2f} | {cw:.2f} | {cc:.2f} | {"yes" if s else "NO"} |'
        for c, a, gw, gm, gc, cw, cc, s in rows]
srv.stop()
open(os.path.join(KIT, 'GPU_NEMO8_BENCH.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
