"""Matmul kernels at the shapes the nemo8 front end and encoder use (per 251-row block).
Checks each kernel against numpy, then times it (20 repeats). Writes GPU_GEMM_BENCH.md.
usage: python3 tools/bench_gemm.py"""
import os
import sys
import numpy as np
KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, KIT)
from gpuport import Arena, Weights, Plan, ops, check
from gpuport.timing import time_op
from gpuport.config import WORK_DIR, merged_shader_dir, STREAM_SHADERS, SHADER_DIR
from gpuport.run import run
SHADERS = merged_shader_dir(extra=(os.path.join(KIT, 'shaders'), STREAM_SHADERS))

rng = np.random.default_rng(5)
SHAPES = [('DFT cos (K=512,N=257)', 251, 512, 257), ('conv2 (K=1584,N=176)', 251, 1584, 176),
          ('subsample (K=3520,N=176)', 251, 3520, 176), ('FF1 (K=176,N=704)', 251, 176, 704)]
rows = []
for name, M, K, N in SHAPES:
    A = (rng.standard_normal((M, K)) * 0.1).astype(np.float32)
    W = (rng.standard_normal((N, K)) * 0.1).astype(np.float32)
    b = (rng.standard_normal(N) * 0.1).astype(np.float32)
    want = A @ W.T + b
    if K % 4 == 0:
        pass
    for kern in ['gemm12', 'gemm12v', 'gemm4', 'gemm_k5']:
        w = Weights()
        mm = w.put_mm4(W, b) if kern == 'gemm_k5' else w.put_mm(W, b, pad=4 if kern == 'gemm4' else 12)
        path = w.save(os.path.join(WORK_DIR, f'gemm_{kern}_{K}_{N}'))
        ar = Arena(); ia = ar.alloc('A', M * K); io = ar.alloc('O', M * N)
        arena = np.zeros(ar.used(), np.float32); arena[ia:ia + M * K] = A.ravel()
        p = Plan()
        {'gemm12': ops.gemm12, 'gemm12v': ops.gemm12v, 'gemm4': ops.gemm4, 'gemm_k5': ops.gemm_k5}[kern](p, ia, M, mm, io)
        got = run(p, arena, io, M * N, weights=path, shader_dir=SHADERS)[0]
        ok = check.compare(f'{kern} {name}', got, want.ravel(), 1e-3, quiet=True)
        ms = time_op(p, arena, io, M * N, repeats=20, weights=path, shader_dir=SHADERS)
        gmac = M * K * N / ms / 1e6
        rows.append((name, kern, ok, ms, gmac))
        print(f'{"ok  " if ok else "FAIL"} {kern:7s} {name:28s} {ms:8.2f} ms  {gmac:.2f} GMAC/s')
out = ['# Matmul kernels at nemo8 shapes (generated by tools/bench_gemm.py)', '',
       'One 251-row block per shape, 20 repeats. GMAC/s = M*K*N / time.', '',
       '| shape | kernel | matches numpy | ms | GMAC/s |', '|---|---|---|---|---|']
out += [f'| {n} | {k} | {"yes" if ok else "NO"} | {ms:.2f} | {g:.2f} |' for n, k, ok, ms, g in rows]
open(os.path.join(KIT, 'GPU_GEMM_BENCH.md'), 'w').write('\n'.join(out) + '\n')
